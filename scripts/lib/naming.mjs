/**
 * Переводит путь переменной Figma в имя пользовательского свойства CSS.
 *
 * Слова из пути режутся по «/», «_» и пробелам, приводятся к нижнему регистру.
 * Повторяющиеся слова убираются — остаётся последнее вхождение: группа в Figma
 * почти всегда продублирована в самом имени переменной («BG/state_bg_accent»).
 * Схлопывание идёт по всему пути целиком, а не только внутри группы: слово
 * «переезжает» на позицию последнего вхождения, поэтому «A/B/A_C» и «B/A_C»
 * дают одинаковый результат. Функция не гарантирует уникальность результата
 * для разных входов — за это отвечает проверка совпадений в parse-export
 * (задача 4).
 *
 * Первое слово (группа Figma) отбрасывается ещё и тогда, когда оно совпадает
 * с каким-либо из последующих слов после отбрасывания конечной «s», при
 * условии, что длина слова не меньше трёх букв — так «Icons/state_icon_...»
 * схлопывается в «state-icon-...», а «Body M/Regular» не теряет «m» из-за
 * ограничения по длине. Общее правило множественного числа применяется
 * только к первому слову, а не ко всем словам подряд.
 *
 * Результат проверяется на пригодность для CSS-идентификатора: допустимы
 * только строчные латинские буквы, цифры и дефисы. Кириллица, скобки, точки
 * и другие символы отклоняются осознанно — пакет токенов отдаётся
 * разработчикам, и такие имена нужно поправить в Figma, а не молча пропустить.
 */
export function toCssVarName(figmaPath) {
  const words = figmaPath
    .split(/[/_\s]+/)
    .map((w) => w.toLowerCase())
    .filter(Boolean);

  if (words.length > 1) {
    const [first, ...rest] = words;
    const singular = first.length >= 3 && first.endsWith('s') ? first.slice(0, -1) : null;
    if (singular && rest.includes(singular)) {
      words.shift();
    }
  }

  const kept = words.filter((word, i) => words.lastIndexOf(word) === i);
  const name = '--' + kept.join('-');

  if (!/^--[a-z0-9][a-z0-9-]*$/.test(name)) {
    throw new Error(
      `Имя «${figmaPath}» переводится в «${name}» — так в CSS нельзя. Переименуйте переменную в Figma.`
    );
  }
  return name;
}
